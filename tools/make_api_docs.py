#!/usr/bin/env python3
"""make_api_docs.py - write the generated parts of docs/API.md from the code.

  python3 tools/make_api_docs.py            rewrite docs/API.md
  python3 tools/make_api_docs.py --check    exit 1 if docs/API.md is out of date (what the test and CI run)

Standard library only. The header tables are read from the C headers, the options of the Python tools from their argparse calls, and the image layout and
memory map from a few lines of C compiled with gcc (so the numbers come from the headers themselves, not from a copy). Everything between the
<!-- api:NAME:start --> and <!-- api:NAME:end --> markers is replaced; the rest of the file is written by hand.
"""
from __future__ import annotations

import argparse
import ast
import functools
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "API.md"

HEADERS = ["bootloader/image.h", "bootloader/update.h", "bootloader/rollback.h", "bootloader/ob_check.h", "bootloader/sha256.h", "bootloader/flash_l0.h",
           "bootloader/nv_eeprom.h", "secure_link/secure_link.h", "secure_link/fcnt_store.h", "secure_link/aes128.h", "secure_link/aes_cmac.h"]
# headers that are deliberately not documented as interfaces, and why
SKIPPED_HEADERS = {"bootloader/pubkey.h": "generated by tools/gen_signing_key.py (the public key)",
                   "secure_link/secure_link_keys.example.h": "template for the secret link keys",
                   "secure_link/secure_link_keys.h": "the secret link keys (generated, never committed)"}
SECURE_LINK_TOOLS = ["secure_link/gen_keys.py", "secure_link/sync_to_feather.sh"]
TEST_DIRS = ["bootloader/test", "secure_link/test"]
LD_BOOTLOADER = "bootloader/bootloader.ld"
LD_APP = ["STM32L072xx_FLASH.ld", "STM32L072CZYX_FLASH.ld"]
FACT_HEADERS = ["image.h", "update.h", "rollback.h", "ob_check.h", "nv_eeprom.h"]   # in bootloader/; their numeric #defines are compiled into the facts


# ---------------------------------------------------------------- reading the headers
def comment_text(lines):
    """The text of a /* ... */ comment given as source lines: markers and leading stars removed, whitespace collapsed."""
    t = " ".join(lines)
    t = re.sub(r"/\*+|\*+/", " ", t)
    t = re.sub(r"(^|\s)\*+(?=\s|$)", " ", t)
    return re.sub(r"\s+", " ", t).strip()


def first_sentence(text):
    """The first sentence of a text (up to the first . ? or ! that is followed by a space or the end), or all of it."""
    m = re.search(r"[.?!](?=\s|$)", text)
    return text[:m.end()] if m else text


def top_comment(text):
    """The comment that opens a C file, as cleaned text without the leading 'name - ' (empty if the file does not open that way)."""
    t = text.lstrip()
    if not t.startswith("/*") or "*/" not in t:
        return ""
    body = comment_text(t[:t.index("*/") + 2].split("\n"))
    m = re.match(r"^[\w/.]+\s+-\s+(.*)$", body)
    return m.group(1) if m else ""


def parse_header(text):
    """Summary, #define constants, typedef struct/enum blocks and function/variable declarations of one header: a dict."""
    lines = text.split("\n")
    constants, functions = [], []
    for ln in lines:
        m = re.match(r"^#define\s+([A-Za-z_]\w*)\s+(.*)$", ln)
        if m:
            value, _, comment = m.group(2).partition("/*")
            value = value.strip()
            if value:
                constants.append((m.group(1), value, comment.replace("*/", "").strip()))
    types = [m.group(0) for m in re.finditer(r"^typedef\s+(?:struct|enum)\s*\{.*?^\}\s*\w+;", text, re.S | re.M)]
    i = 0
    while i < len(lines):
        ln = lines[i]
        is_var = re.match(r'^extern\s+(?!"C")', ln)
        is_fn = (not is_var) and re.match(r'^(?!typedef\b|#|/\*|\*|\}|extern\s+"C")[A-Za-z_][\w \t*]*?\b(\w+)\s*\(', ln)
        if is_var or is_fn:
            j = i
            while ";" not in lines[j]:
                j += 1
            decl = " ".join(x.strip() for x in lines[i:j + 1])
            inline = re.search(r"/\*(.*?)\*/", decl)
            decl = re.sub(r"/\*.*?\*/", "", decl).rstrip(";").strip()
            decl = re.sub(r"\s+", " ", decl)
            if is_var:
                m = re.search(r"\(\s*\*\s*(\w+)\s*\)", decl) or re.search(r"(\w+)$", decl)
            else:
                m = is_fn
            comment = comment_text([inline.group(0)]) if inline else ""
            if not comment and i > 0 and lines[i - 1].rstrip().endswith("*/"):
                k = i - 1
                while "/*" not in lines[k]:
                    k -= 1
                comment = comment_text(lines[k:i])
            functions.append((m.group(1), decl, comment))
            i = j
        i += 1
    return {"summary": first_sentence(top_comment(text)), "constants": constants, "types": types, "functions": functions}


def header_comment_table(text):
    """The hand-written field table in image.h's top comment: [(offset, size, name, meaning)]."""
    head = text[:text.index("*/")]
    return [(int(m.group(1)), int(m.group(2)), m.group(3), m.group(4).strip())
            for m in re.finditer(r"^\s*\*\s+(\d+)\s+(\d+)\s+(\w+)\s+(.*)$", head, re.M)]


# ---------------------------------------------------------------- facts compiled from the headers
@functools.lru_cache(maxsize=None)
def c_facts():
    """The image-header layout and every numeric constant of the bootloader headers, as the C compiler sees them: {fields, sizeof, consts}."""
    image = (ROOT / "bootloader" / "image.h").read_text(encoding="utf-8")
    struct = parse_header(image)["types"]
    body = next(t for t in struct if t.rstrip().endswith("img_header;"))
    members = re.findall(r"\b(?:uint\d+_t)\s+(\w+)(?:\[\d+\])?\s*;", body)
    names = []
    for h in FACT_HEADERS:
        names += [c for c, v, _ in parse_header((ROOT / "bootloader" / h).read_text(encoding="utf-8"))["constants"] if v[0].isdigit() or v[0] == "("]
    prog = ["#include <stdio.h>", "#include <stddef.h>"] + [f'#include "{h}"' for h in FACT_HEADERS] + ["int main(void) {"]
    prog += [f'  printf("field {m} %zu %zu\\n", offsetof(img_header, {m}), sizeof(((img_header *)0)->{m}));' for m in members]
    prog += ['  printf("sizeof %zu\\n", sizeof(img_header));']
    prog += [f'  printf("const {n} %llu\\n", (unsigned long long)({n}));' for n in names]
    prog += ["  return 0;", "}"]
    with tempfile.TemporaryDirectory() as d:
        src, exe = Path(d) / "facts.c", Path(d) / "facts"
        src.write_text("\n".join(prog) + "\n", encoding="utf-8")
        r = subprocess.run(["gcc", "-std=gnu11", "-Wall", "-Wextra", "-Werror", "-I", str(ROOT / "bootloader"), "-o", str(exe), str(src)], capture_output=True, text=True)
        if r.returncode:
            sys.exit("make_api_docs: could not compile the layout program with gcc:\n" + r.stderr)
        out = subprocess.run([str(exe)], capture_output=True, text=True, check=True).stdout
    facts = {"fields": [], "sizeof": 0, "consts": {}}
    for line in out.splitlines():
        p = line.split()
        if p[0] == "field":
            facts["fields"].append((p[1], int(p[2]), int(p[3])))
        elif p[0] == "sizeof":
            facts["sizeof"] = int(p[1])
        else:
            facts["consts"][p[1]] = int(p[2])
    return facts


def parse_size(token):
    """A linker-script length such as 24K, 20K or 0x11E00, in bytes."""
    token = token.strip()
    return int(token[:-1]) * 1024 if token.upper().endswith("K") else int(token, 0)


def linker_regions(path):
    """{'FLASH': (origin, length), 'RAM': (origin, length)} from a linker script's MEMORY block."""
    text = (ROOT / path).read_text(encoding="utf-8")
    out = {}
    for name in ("FLASH", "RAM"):
        m = re.search(rf"^\s*{name}\s*\(\w+\)\s*:\s*ORIGIN\s*=\s*(0x[0-9A-Fa-f]+)\s*,\s*LENGTH\s*=\s*([0-9A-Fa-fxX]+K?)", text, re.M)
        if m:
            out[name] = (int(m.group(1), 16), parse_size(m.group(2)))
    return out


def fmt_size(n):
    return f"{n // 1024} KB" if n % 1024 == 0 else f"{n:,} B"


def addr(n):
    return f"0x{n:08X}"


# ---------------------------------------------------------------- the generated sections
def esc(s):
    return s.replace("|", "\\|")


def section_c():
    out = []
    for rel in HEADERS:
        info = parse_header((ROOT / rel).read_text(encoding="utf-8"))
        out += [f"#### `{rel}`", "", info["summary"], ""]
        if info["functions"]:
            out += ["| Name | Declaration | What it does |", "|---|---|---|"]
            out += [f"| `{n}` | `{esc(d)}` | {esc(c)} |" for n, d, c in info["functions"]]
            out.append("")
        if info["constants"]:
            out += ["| Constant | Value | Meaning |", "|---|---|---|"]
            out += [f"| `{n}` | `{esc(v)}` | {esc(c)} |" for n, v, c in info["constants"]]
            out.append("")
        for t in info["types"]:
            out += ["```c", t, "```", ""]
    return "\n".join(out).rstrip("\n")


def section_layout():
    f = c_facts()
    table = {off: meaning for off, _, _, meaning in header_comment_table((ROOT / "bootloader" / "image.h").read_text(encoding="utf-8"))}
    k = f["consts"]
    out = [f"The header is {f['sizeof']} bytes (`IMG_HDR_SIZE` = {k['IMG_HDR_SIZE']}), little-endian, read from the compiled `img_header` structure. "
           f"The SHA-256 covers header bytes 0 to {k['IMG_FIXED_LEN'] - 1} (`IMG_FIXED_LEN` = {k['IMG_FIXED_LEN']}) followed by the application.", "",
           "| Offset | Size | Field | Meaning (from `image.h`) |", "|---|---|---|---|"]
    out += [f"| {off} | {size} | `{name}` | {esc(table.get(off, ''))} |" for name, off, size in f["fields"]]
    out += ["", f"`IMG_MAGIC` = `0x{k['IMG_MAGIC']:08X}`, `IMG_HDR_VERSION` = {k['IMG_HDR_VERSION']}."]
    return "\n".join(out)


def section_memory():
    k = c_facts()["consts"]
    boot, app = linker_regions(LD_BOOTLOADER), linker_regions(LD_APP[0])
    rows = [("Bootloader", boot["FLASH"][0], boot["FLASH"][1], f"`{LD_BOOTLOADER}`"),
            ("Slot A (header, then application)", k["SLOT_A_BASE"], k["SLOT_SIZE"], "`bootloader/image.h`"),
            ("&nbsp;&nbsp;header", k["SLOT_A_BASE"], k["IMG_HDR_SIZE"], "`bootloader/image.h`"),
            ("&nbsp;&nbsp;application", k["APP_BASE"], k["IMG_MAX_SIZE"], f"`bootloader/image.h`; `{LD_APP[0]}` (FLASH)"),
            ("Slot B (update)", k["SLOT_B_BASE"], k["SLOT_SIZE"], "`bootloader/image.h`"),
            ("Data EEPROM: anti-rollback record", k["ROLLBACK_EEPROM_ADDR"], k["ROLLBACK_WORDS"] * 4, "`bootloader/nv_eeprom.h`, `bootloader/rollback.h`"),
            ("RAM", boot["RAM"][0], boot["RAM"][1], f"`{LD_BOOTLOADER}`")]
    out = ["| Region | Start | Last byte | Size | Defined in |", "|---|---|---|---|---|"]
    out += [f"| {n} | `{addr(s)}` | `{addr(s + size - 1)}` | {fmt_size(size)} | {src} |" for n, s, size, src in rows]
    out += ["", f"The application is linked at `{addr(app['FLASH'][0])}` for {fmt_size(app['FLASH'][1])}: its first byte is the first byte after the header."]
    return "\n".join(out)


def first_paragraph(doc):
    return re.sub(r"\s+", " ", (doc or "").strip().split("\n\n")[0]).strip()


def argparse_rows(tree):
    rows = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "add_argument":
            names = [a.value for a in node.args if isinstance(a, ast.Constant) and isinstance(a.value, str)]
            kw = {k.arg: k.value for k in node.keywords}

            def lit(key):
                try:
                    return ast.literal_eval(kw[key]) if key in kw else None
                except ValueError:
                    return None
            extra = []
            if lit("required"):
                extra.append("required")
            if lit("default") is not None:
                extra.append(f"default `{lit('default')}`")
            if lit("choices"):
                extra.append("one of " + ", ".join(f"`{c}`" for c in lit("choices")))
            rows.append((", ".join(f"`{n}`" for n in names), " ".join((lit("help") or "").split()), "; ".join(extra)))
    return rows


def tool_files():
    return sorted(str(p.relative_to(ROOT)).replace("\\", "/") for p in (ROOT / "tools").iterdir() if p.suffix in (".py", ".sh")) + SECURE_LINK_TOOLS


def section_tools():
    out = []
    for rel in tool_files():
        text = (ROOT / rel).read_text(encoding="utf-8")
        out += [f"#### `{rel}`", ""]
        if rel.endswith(".py"):
            tree = ast.parse(text)
            out += [re.sub(r"^[\w./-]+\s+-\s+", "", first_paragraph(ast.get_docstring(tree))), ""]
            rows = argparse_rows(tree)
            if rows:
                out += ["| Option | What it does | Notes |", "|---|---|---|"] + [f"| {n} | {esc(h)} | {x} |" for n, h, x in rows] + [""]
        else:
            block = []
            for ln in text.split("\n")[1:]:
                if not ln.startswith("#"):
                    break
                block.append(ln.lstrip("#")[1:] if ln.startswith("# ") else ln.lstrip("#"))
            para = []
            for b in block:
                if not b.strip():
                    break
                para.append(b.strip())
            out += [first_sentence(re.sub(r"^[\w./-]+\s+-\s+", "", " ".join(para))), "", "```text", *block, "```", ""]
    return "\n".join(out).rstrip("\n")


def test_programs(rel_dir):
    return sorted(p.name for p in (ROOT / rel_dir).glob("test_*.c"))


def section_tests():
    out = ["| Program | What it checks | Built and run by |", "|---|---|---|"]
    for d in TEST_DIRS:
        for name in test_programs(d):
            text = (ROOT / d / name).read_text(encoding="utf-8")
            out.append(f"| `{d}/{name}` | {esc(first_sentence(top_comment(text)))} | `make -C {d} test` |")
    return "\n".join(out)


def section_doctests():
    tree = ast.parse((ROOT / "tests" / "test_docs.py").read_text(encoding="utf-8"))
    tests = sorted((n for n in ast.walk(tree) if isinstance(n, ast.FunctionDef) and n.name.startswith("test_")), key=lambda n: n.lineno)
    return "\n".join(f"- {first_paragraph(ast.get_docstring(n))}" for n in tests)


SECTIONS = {"c": section_c, "layout": section_layout, "memory": section_memory, "tools": section_tools, "tests": section_tests, "doctests": section_doctests}


def fill(doc):
    """docs/API.md with every generated section rewritten. Raises SystemExit if a marker is missing."""
    for name, fn in SECTIONS.items():
        start, end = f"<!-- api:{name}:start -->", f"<!-- api:{name}:end -->"
        if start not in doc or end not in doc:
            sys.exit(f"make_api_docs: {DOC} has no '{start}' ... '{end}' markers")
        a, b = doc.index(start) + len(start), doc.index(end)
        doc = doc[:a] + "\n" + fn() + "\n" + doc[b:]
    return doc


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if docs/API.md is out of date")
    a = ap.parse_args(argv)
    current = DOC.read_text(encoding="utf-8")
    new = fill(current.replace("\r\n", "\n"))
    if a.check:
        if new != current.replace("\r\n", "\n"):
            print("docs/API.md is out of date: run  python3 tools/make_api_docs.py", file=sys.stderr)
            return 1
        print("docs/API.md is up to date")
        return 0
    if new == current:
        print("docs/API.md already up to date")
    else:
        DOC.write_text(new, encoding="utf-8", newline="\n")
        print("docs/API.md updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
